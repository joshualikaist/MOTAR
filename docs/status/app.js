(async function(){
  // Data panels + prose render regardless of whether WebGL/CDN is available.
  try{ renderStatic(); }catch(e){ console.error('renderStatic',e); }
  // render immediately from the embedded snapshot so panels always populate,
  const renderAll=(s)=>{ renderLatest(s); renderCurve(s); renderRuns(s); };
  try{ renderAll(fallbackStatus()); }catch(e){ console.error('fallback render',e); }
  // then upgrade to the live status.json if it is reachable (same-origin http).
  try{ const s=await fetchStatus(); renderAll(s); }
  catch(e){ document.getElementById('tag-live').textContent='● snapshot'; }
  // 3D scene is best-effort: guard so a missing three.js CDN never blocks the page.
  try{
    if(typeof THREE==='undefined'||!THREE.OrbitControls) throw new Error('three.js unavailable');
    window.__mo=Arena;
    Arena.init(document.getElementById('stage'));
    wire();
  }catch(e){
    console.error('3D init',e);
    const st=document.getElementById('stage');
    if(st) st.innerHTML='<div class="hud" style="position:static;margin:16px">3D 뷰를 불러오지 못했습니다 (three.js CDN 필요) · 인터넷 연결 후 새로고침</div>';
    document.querySelectorAll('.controls input,.controls button').forEach(el=>el.disabled=true);
  }
})();
