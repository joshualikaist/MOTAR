/* ---------------- controls wiring ---------------- */
function wire(){
  const bars=document.getElementById('sl-bars'), speed=document.getElementById('sl-speed');
  const lblB=document.getElementById('lbl-bars'), lblS=document.getElementById('lbl-speed');
  const hudB=document.getElementById('hud-bars'), hudD=document.getElementById('hud-density');
  const upd=()=>{const n=+bars.value;lblB.textContent=n;hudB.textContent=n;hudD.textContent=perc100(n);Arena.setBars(n);};
  bars.addEventListener('input',upd);
  speed.addEventListener('input',()=>{const v=+speed.value/10;lblS.textContent=v.toFixed(1);Arena.setSpeed(v);});
  const play=document.getElementById('btn-play');
  let playing=true;
  play.addEventListener('click',()=>{playing=!playing;Arena.setPlaying(playing);play.textContent=playing?'⏸ 일시정지':'▶ 재생';});
  document.getElementById('cb-lidar').addEventListener('change',e=>Arena.setLidar(e.target.checked));
  document.getElementById('btn-preset').addEventListener('click',()=>{bars.value=110;upd();});
}

